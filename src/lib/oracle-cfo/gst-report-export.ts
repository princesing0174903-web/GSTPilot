// CSV EXPORT
// ═══════════════════════════════════════════════════════════════════════════════

export function generateGSTReportCSV(report: GSTReport): { buffer: Buffer; base64: string } {
  const lines: string[] = [];
  const calc = report.calculations;

  lines.push('GSTPilot GST Report');
  lines.push(`Report Type,${report.intent.reportType.toUpperCase()}`);
  lines.push(`Period,${report.intent.periodLabel}`);
  lines.push(`Date Range,${report.intent.startDate} to ${report.intent.endDate}`);
  lines.push(`Generated,${new Date(report.generatedAt).toISOString()}`);
  lines.push(`Generated By,${report.generatedBy}`);
  lines.push(`Report ID,${report.reportId}`);
  lines.push('');

  lines.push('EXECUTIVE SUMMARY');
  lines.push('Metric,Value');
  lines.push(`Taxable Turnover,${calc.totalTaxableTurnover}`);
  lines.push(`Total Output Tax,${calc.totalOutputTax}`);
  lines.push(`ITC Available,${calc.itcAvailable}`);
  lines.push(`ITC Utilized,${calc.itcUtilized}`);
  lines.push(`Net GST Payable,${calc.netPayable}`);
  lines.push(`Exempt Supplies,${calc.totalExempt}`);
  lines.push(`Zero-Rated,${calc.totalZeroRated}`);
  lines.push(`Export,${calc.totalExport}`);
  lines.push(`Refund Eligible,${calc.refundEligible}`);
  lines.push('');

  lines.push('SALES BY SLAB');
  lines.push('Slab,Invoice Count,Taxable Value,CGST,SGST,IGST,Cess,Total Tax,Total Amount');
  for (const s of calc.salesBySlab) {
    lines.push(`${s.gstRate}%,${s.invoiceCount},${s.taxableValue},${s.cgst},${s.sgst},${s.igst},${s.cess},${s.totalTax},${s.totalAmount}`);
  }
  lines.push(`TOTAL,${calc.salesBySlab.reduce((s, r) => s + r.invoiceCount, 0)},${calc.totalTaxableTurnover},${calc.outputCGST},${calc.outputSGST},${calc.outputIGST},${calc.outputCess},${calc.totalOutputTax},${calc.totalTaxableTurnover + calc.totalOutputTax}`);
  lines.push('');

  lines.push('PURCHASES BY SLAB');
  lines.push('Slab,Invoice Count,Taxable Value,CGST,SGST,IGST,Cess,Total ITC');
  for (const s of calc.purchasesBySlab) {
    lines.push(`${s.gstRate}%,${s.invoiceCount},${s.taxableValue},${s.cgst},${s.sgst},${s.igst},${s.cess},${s.totalTax}`);
  }
  lines.push(`TOTAL,${calc.purchasesBySlab.reduce((s, r) => s + r.invoiceCount, 0)},${calc.purchasesBySlab.reduce((s, r) => s + r.taxableValue, 0)},${calc.itcCGST},${calc.itcSGST},${calc.itcIGST},${calc.itcCess},${calc.itcAvailable}`);
  lines.push('');

  lines.push('GST LIABILITY');
  lines.push('Component,Amount');
  lines.push(`Output CGST,${calc.outputCGST}`);
  lines.push(`Output SGST,${calc.outputSGST}`);
  lines.push(`Output IGST,${calc.outputIGST}`);
  lines.push(`Output Cess,${calc.outputCess}`);
  lines.push(`Total Output Tax,${calc.totalOutputTax}`);
  lines.push(`Less: ITC Utilized,-${calc.itcUtilized}`);
  lines.push(`Net CGST Payable,${calc.netCGSTPayable}`);
  lines.push(`Net SGST Payable,${calc.netSGSTPayable}`);
  lines.push(`Net IGST Payable,${calc.netIGSTPayable}`);
  lines.push(`Net Cess Payable,${calc.netCessPayable}`);
  lines.push(`Net GST Payable,${calc.netPayable}`);
  lines.push('');

  lines.push('TOP CUSTOMERS');
  lines.push('Customer,GSTIN,Invoice Count,Taxable Value,Tax Amount,Total Amount');
  for (const c of report.topCustomers) {
    lines.push(`"${c.name}",${c.gstin ?? ''},${c.invoiceCount},${c.taxableValue},${c.taxAmount},${c.totalAmount}`);
  }
  lines.push('');

  lines.push('TOP VENDORS');
  lines.push('Vendor,GSTIN,Invoice Count,Taxable Value,ITC Amount,Total Amount');
  for (const v of report.topVendors) {
    lines.push(`"${v.name}",${v.gstin ?? ''},${v.invoiceCount},${v.taxableValue},${v.taxAmount},${v.totalAmount}`);
  }
  lines.push('');

  lines.push('VALIDATION SUMMARY');
  lines.push(`Invoices Checked,${report.validation.totalChecked}`);
  lines.push(`Passed,${report.validation.passed}`);
  lines.push(`Critical Issues,${report.validation.criticalCount}`);
  lines.push(`Warnings,${report.validation.warningCount}`);
  lines.push(`Info,${report.validation.infoCount}`);
  lines.push(`Duplicate Invoice Numbers,${report.validation.duplicateInvoiceNumbers.length}`);
  lines.push(`Invalid GSTINs,${report.validation.invalidGstins.length}`);
  lines.push(`Future-Dated Invoices,${report.validation.futureDatedInvoices.length}`);
  lines.push(`Reverse-Charge Invoices,${report.validation.reverseChargeInvoices.length}`);
  lines.push(`Exempt Invoices,${report.validation.exemptInvoices.length}`);
  lines.push(`Zero-Rated Invoices,${report.validation.zeroRatedInvoices.length}`);
  lines.push(`Export Invoices,${report.validation.exportInvoices.length}`);
  lines.push('');

  if (report.validation.issues.length > 0) {
    lines.push('VALIDATION ISSUES');
    lines.push('Invoice ID,Invoice Number,Severity,Field,Message,Value');
    for (const i of report.validation.issues) {
      lines.push(`${i.invoiceId},"${i.invoiceNumber}",${i.severity},${i.field},"${i.message.replace(/"/g, '""')}","${i.value}"`);
    }
    lines.push('');
  }

  lines.push('CROSS-CHECKS');
  lines.push('Check,Expected,Actual,Status');
  for (const c of calc.crossChecks) {
    lines.push(`"${c.label}",${c.expected},${c.actual},${c.match ? 'PASS' : 'FAIL'}`);
  }
  lines.push('');

  lines.push('MONTHLY COMPARISON');
  lines.push('Period,Taxable Value,Output Tax,ITC,Net Payable');
  for (const m of report.monthlyComparison) {
    lines.push(`${m.periodLabel},${m.taxableValue},${m.outputTax},${m.itc},${m.netPayable}`);
  }
  lines.push('');

  lines.push('ORACLE INSIGHTS');
  lines.push('#,Insight');
  report.insights.forEach((s, i) => lines.push(`${i + 1},"${s.replace(/"/g, '""')}"`));
  lines.push('');
  lines.push('RECOMMENDED ACTIONS');
  lines.push('#,Action');
  report.recommendations.forEach((s, i) => lines.push(`${i + 1},"${s.replace(/"/g, '""')}"`));

  const csv = lines.join('\n');
  const buffer = Buffer.from(csv, 'utf-8');
  return { buffer, base64: buffer.toString('base64') };
}
