// ═══════════════════════════════════════════════════════════════════════════════
// GSTPilot Oracle CFO™ — GST Report Exporter (PDF / Excel / CSV)
//
// Generates downloadable GST report files from a structured GSTReport.
//
// Three formats:
//   • PDF  — professional multi-section report (uses pdfkit, matches invoice-pdf style)
//   • Excel — multi-sheet workbook (uses xlsx/SheetJS)
//   • CSV  — flat CSV with all key metrics
//
// All three are pure-data exports — no fake values, every number comes from
// the GSTReport passed in. The /export API route picks the format and streams
// the buffer back.
// ═══════════════════════════════════════════════════════════════════════════════

import type { GSTReport } from './gst-report-engine';

// ─── Colors (matching invoice-pdf.ts for visual consistency) ──────────────

const EMERALD = '#10b981';
const DARK = '#0a0a0a';
const GRAY = '#666666';
const LIGHT_GRAY = '#e5e5e5';
const BG_LIGHT = '#f9fafb';
const AMBER = '#f59e0b';
const ROSE = '#ef4444';

// ═══════════════════════════════════════════════════════════════════════════════
// PDF EXPORT
// ═══════════════════════════════════════════════════════════════════════════════

export async function generateGSTReportPDF(report: GSTReport): Promise<{ buffer: Buffer; base64: string }> {
  const PDFDocument = (await import('pdfkit')).default;
  const doc = new PDFDocument({ size: 'A4', margin: 50 });
  const chunks: Buffer[] = [];
  doc.on('data', (chunk: Buffer) => chunks.push(chunk));
  const pdfPromise = new Promise<Buffer>((resolve) => {
    doc.on('end', () => resolve(Buffer.concat(chunks)));
  });

  const W = 595; // A4 width in points
  const M = 50;
  const CW = W - M * 2;

  // ═══ HEADER ═══
  doc.save();
  doc.rect(0, 0, W, 6).fill(EMERALD);
  doc.restore();

  doc.save();
  doc.roundedRect(M, 30, 44, 44, 10).fill(EMERALD);
  doc.fillColor('#ffffff').fontSize(26).font('Helvetica-Bold');
  doc.text('G', M + 14, 38);
  doc.restore();

  doc.fillColor(DARK).fontSize(22).font('Helvetica-Bold');
  doc.text('GSTPilot', M + 56, 32);

  doc.fillColor(GRAY).fontSize(9).font('Helvetica');
  doc.text('GST Report — Generated by Oracle CFO™', M + 56, 58);

  doc.fontSize(10).font('Helvetica-Bold');
  doc.text(report.intent.reportType.toUpperCase(), W - M - 100, 30, { width: 100, align: 'right' });
  doc.font('Helvetica').fillColor(GRAY).fontSize(9);
  doc.text(report.intent.periodLabel, W - M - 100, 46, { width: 100, align: 'right' });
  doc.text(`Generated ${new Date(report.generatedAt).toLocaleDateString('en-IN')}`, W - M - 100, 60, { width: 100, align: 'right' });

  doc.save();
  doc.moveTo(M, 90).lineTo(W - M, 90).strokeColor(LIGHT_GRAY).lineWidth(1).stroke();
  doc.restore();

  // ═══ SELLER / ORG DETAILS ═══
  let y = 105;
  doc.fillColor(DARK).fontSize(11).font('Helvetica-Bold');
  doc.text(report.dataSummary ? 'Organization Details' : '', M, y);
  y += 16;
  doc.font('Helvetica').fillColor(GRAY).fontSize(9);
  if (report.intent.branch) {
    doc.text(`Branch: ${report.intent.branch}`, M, y); y += 12;
  }
  doc.text(`Report ID: ${report.reportId}`, M, y); y += 12;
  doc.text(`Period: ${report.intent.startDate} → ${report.intent.endDate}`, M, y); y += 18;

  // ═══ EXECUTIVE SUMMARY (KPI cards) ═══
  doc.fillColor(DARK).fontSize(13).font('Helvetica-Bold');
  doc.text('Executive Summary', M, y);
  y += 20;

  const calc = report.calculations;
  const kpis = [
    { label: 'Taxable Turnover', value: `₹${calc.totalTaxableTurnover.toLocaleString('en-IN')}` },
    { label: 'Total Output Tax', value: `₹${calc.totalOutputTax.toLocaleString('en-IN')}` },
    { label: 'ITC Available', value: `₹${calc.itcAvailable.toLocaleString('en-IN')}` },
    { label: 'Net GST Payable', value: `₹${calc.netPayable.toLocaleString('en-IN')}`, highlight: true },
    { label: 'Exempt Supplies', value: `₹${calc.totalExempt.toLocaleString('en-IN')}` },
    { label: 'Zero-Rated (Export)', value: `₹${(calc.totalZeroRated + calc.totalExport).toLocaleString('en-IN')}` },
  ];

  const cardW = (CW - 20) / 3;
  const cardH = 50;
  for (let i = 0; i < kpis.length; i++) {
    const kpi = kpis[i];
    const col = i % 3;
    const row = Math.floor(i / 3);
    const x = M + col * (cardW + 10);
    const cy = y + row * (cardH + 10);
    doc.save();
    doc.roundedRect(x, cy, cardW, cardH, 6).fillAndStroke(kpi.highlight ? EMERALD : BG_LIGHT, kpi.highlight ? EMERALD : LIGHT_GRAY);
    doc.fillColor(kpi.highlight ? '#ffffff' : GRAY).fontSize(8).font('Helvetica');
    doc.text(kpi.label.toUpperCase(), x + 8, cy + 8, { width: cardW - 16 });
    doc.fillColor(kpi.highlight ? '#ffffff' : DARK).fontSize(13).font('Helvetica-Bold');
    doc.text(kpi.value, x + 8, cy + 22, { width: cardW - 16 });
    doc.restore();
  }
  y += Math.ceil(kpis.length / 3) * (cardH + 10) + 10;

  // ═══ SALES SUMMARY (by slab) ═══
  y = drawSectionHeader(doc, 'Sales Summary (Outward Supplies)', M, y, W);
  const salesRows: Array<{ cols: string[]; bold?: boolean }> = [
    { cols: ['Slab', 'Invoices', 'Taxable', 'CGST', 'SGST', 'IGST', 'Total Tax'], bold: true },
    ...calc.salesBySlab.map((s) => ({
      cols: [
        `${s.gstRate}%`,
        String(s.invoiceCount),
        `₹${s.taxableValue.toLocaleString('en-IN')}`,
        `₹${s.cgst.toLocaleString('en-IN')}`,
        `₹${s.sgst.toLocaleString('en-IN')}`,
        `₹${s.igst.toLocaleString('en-IN')}`,
        `₹${s.totalTax.toLocaleString('en-IN')}`,
      ],
    })),
    {
      cols: [
        'TOTAL',
        String(calc.salesBySlab.reduce((s, r) => s + r.invoiceCount, 0)),
        `₹${calc.totalTaxableTurnover.toLocaleString('en-IN')}`,
        `₹${calc.outputCGST.toLocaleString('en-IN')}`,
        `₹${calc.outputSGST.toLocaleString('en-IN')}`,
        `₹${calc.outputIGST.toLocaleString('en-IN')}`,
        `₹${calc.totalOutputTax.toLocaleString('en-IN')}`,
      ],
      bold: true,
    },
  ];
  y = drawTable(doc, salesRows, [60, 60, 95, 80, 80, 80, 90], M, y, W);

  // ═══ PURCHASE SUMMARY (by slab) ═══
  y = ensureSpace(doc, y, 120);
  y = drawSectionHeader(doc, 'Purchase Summary (Inward Supplies / ITC)', M, y, W);
  const purchaseRows: Array<{ cols: string[]; bold?: boolean }> = [
    { cols: ['Slab', 'Invoices', 'Taxable', 'CGST', 'SGST', 'IGST', 'ITC'], bold: true },
    ...calc.purchasesBySlab.map((s) => ({
      cols: [
        `${s.gstRate}%`,
        String(s.invoiceCount),
        `₹${s.taxableValue.toLocaleString('en-IN')}`,
        `₹${s.cgst.toLocaleString('en-IN')}`,
        `₹${s.sgst.toLocaleString('en-IN')}`,
        `₹${s.igst.toLocaleString('en-IN')}`,
        `₹${s.totalTax.toLocaleString('en-IN')}`,
      ],
    })),
    {
      cols: [
        'TOTAL',
        String(calc.purchasesBySlab.reduce((s, r) => s + r.invoiceCount, 0)),
        `₹${calc.purchasesBySlab.reduce((s, r) => s + r.taxableValue, 0).toLocaleString('en-IN')}`,
        `₹${calc.itcCGST.toLocaleString('en-IN')}`,
        `₹${calc.itcSGST.toLocaleString('en-IN')}`,
        `₹${calc.itcIGST.toLocaleString('en-IN')}`,
        `₹${calc.itcAvailable.toLocaleString('en-IN')}`,
      ],
      bold: true,
    },
  ];
  y = drawTable(doc, purchaseRows, [60, 60, 95, 80, 80, 80, 90], M, y, W);

  // ═══ GST LIABILITY BREAKDOWN ═══
  y = ensureSpace(doc, y, 200);
  y = drawSectionHeader(doc, 'GST Liability Breakdown', M, y, W);
  const liabilityRows: Array<{ cols: string[]; bold?: boolean; highlight?: boolean }> = [
    { cols: ['Output CGST', `₹${calc.outputCGST.toLocaleString('en-IN')}`] },
    { cols: ['Output SGST', `₹${calc.outputSGST.toLocaleString('en-IN')}`] },
    { cols: ['Output IGST', `₹${calc.outputIGST.toLocaleString('en-IN')}`] },
    { cols: ['Output Cess', `₹${calc.outputCess.toLocaleString('en-IN')}`] },
    { cols: ['Total Output Tax', `₹${calc.totalOutputTax.toLocaleString('en-IN')}`], bold: true },
    { cols: ['Less: ITC Utilized', `−₹${calc.itcUtilized.toLocaleString('en-IN')}`] },
    { cols: ['Net CGST Payable', `₹${calc.netCGSTPayable.toLocaleString('en-IN')}`] },
    { cols: ['Net SGST Payable', `₹${calc.netSGSTPayable.toLocaleString('en-IN')}`] },
    { cols: ['Net IGST Payable', `₹${calc.netIGSTPayable.toLocaleString('en-IN')}`] },
    { cols: ['Net Cess Payable', `₹${calc.netCessPayable.toLocaleString('en-IN')}`] },
    { cols: ['Net GST Payable', `₹${calc.netPayable.toLocaleString('en-IN')}`], bold: true, highlight: true },
  ];
  y = drawKeyValueTable(doc, liabilityRows, M, y, W);

  // ═══ ITC SUMMARY ═══
  y = ensureSpace(doc, y, 150);
  y = drawSectionHeader(doc, 'ITC Summary', M, y, W);
  const itcRows: Array<{ cols: string[]; bold?: boolean }> = [
    { cols: ['ITC Available (CGST)', `₹${calc.itcCGST.toLocaleString('en-IN')}`] },
    { cols: ['ITC Available (SGST)', `₹${calc.itcSGST.toLocaleString('en-IN')}`] },
    { cols: ['ITC Available (IGST)', `₹${calc.itcIGST.toLocaleString('en-IN')}`] },
    { cols: ['ITC Available (Cess)', `₹${calc.itcCess.toLocaleString('en-IN')}`] },
    { cols: ['Total ITC Available', `₹${calc.itcAvailable.toLocaleString('en-IN')}`], bold: true },
    { cols: ['ITC Reversed (Rule 42/43)', `−₹${calc.itcReversed.toLocaleString('en-IN')}`] },
    { cols: ['ITC Utilized', `₹${calc.itcUtilized.toLocaleString('en-IN')}`] },
    { cols: ['Refund Eligible', `₹${calc.refundEligible.toLocaleString('en-IN')}`] },
  ];
  y = drawKeyValueTable(doc, itcRows, M, y, W);

  // ═══ TOP CUSTOMERS ═══
  y = ensureSpace(doc, y, 100);
  y = drawSectionHeader(doc, 'Top Customers (by tax contribution)', M, y, W);
  const customerRows: Array<{ cols: string[]; bold?: boolean }> = [
    { cols: ['Customer', 'Invoices', 'Taxable', 'Tax'], bold: true },
    ...report.topCustomers.slice(0, 10).map((c) => ({
      cols: [
        c.name + (c.gstin ? ` (${c.gstin})` : ''),
        String(c.invoiceCount),
        `₹${c.taxableValue.toLocaleString('en-IN')}`,
        `₹${c.taxAmount.toLocaleString('en-IN')}`,
      ],
    })),
  ];
  y = drawTable(doc, customerRows, [200, 70, 130, 130], M, y, W);

  // ═══ TOP VENDORS ═══
  y = ensureSpace(doc, y, 100);
  y = drawSectionHeader(doc, 'Top Vendors (by ITC contribution)', M, y, W);
  const vendorRows: Array<{ cols: string[]; bold?: boolean }> = [
    { cols: ['Vendor', 'Invoices', 'Taxable', 'ITC'], bold: true },
    ...report.topVendors.slice(0, 10).map((v) => ({
      cols: [
        v.name + (v.gstin ? ` (${v.gstin})` : ''),
        String(v.invoiceCount),
        `₹${v.taxableValue.toLocaleString('en-IN')}`,
        `₹${v.taxAmount.toLocaleString('en-IN')}`,
      ],
    })),
  ];
  y = drawTable(doc, vendorRows, [200, 70, 130, 130], M, y, W);

  // ═══ VALIDATION REPORT ═══
  y = ensureSpace(doc, y, 100);
  y = drawSectionHeader(doc, `Validation Report (${report.validation.criticalCount} critical, ${report.validation.warningCount} warnings, ${report.validation.infoCount} info)`, M, y, W);
  const val = report.validation;
  const valSummary: Array<{ cols: string[]; bold?: boolean }> = [
    { cols: ['Invoices checked', String(val.totalChecked)] },
    { cols: ['Passed validation', String(val.passed)] },
    { cols: ['Critical issues', String(val.criticalCount)], bold: val.criticalCount > 0 },
    { cols: ['Warnings', String(val.warningCount)] },
    { cols: ['Info (RCM, exempt, etc.)', String(val.infoCount)] },
    { cols: ['Duplicate invoice numbers', String(val.duplicateInvoiceNumbers.length)] },
    { cols: ['Invalid GSTINs', String(val.invalidGstins.length)] },
    { cols: ['Future-dated invoices', String(val.futureDatedInvoices.length)] },
    { cols: ['Reverse-charge invoices', String(val.reverseChargeInvoices.length)] },
    { cols: ['Exempt / nil-rated invoices', String(val.exemptInvoices.length)] },
    { cols: ['Zero-rated invoices', String(val.zeroRatedInvoices.length)] },
    { cols: ['Export invoices', String(val.exportInvoices.length)] },
  ];
  y = drawKeyValueTable(doc, valSummary, M, y, W);

  // Top 10 critical issues (if any)
  if (val.criticalCount > 0) {
    y = ensureSpace(doc, y, 80);
    doc.fillColor(ROSE).fontSize(10).font('Helvetica-Bold');
    doc.text('Top Critical Issues', M, y);
    y += 14;
    doc.font('Helvetica').fillColor(GRAY).fontSize(8);
    for (const issue of val.issues.filter((i) => i.severity === 'critical').slice(0, 10)) {
      y = ensureSpace(doc, y, 30);
      doc.fillColor(DARK).font('Helvetica-Bold').fontSize(8);
      doc.text(`${issue.invoiceNumber} [${issue.field}]`, M, y);
      y += 10;
      doc.fillColor(GRAY).font('Helvetica').fontSize(8);
      doc.text(issue.message, M + 10, y, { width: CW - 20 });
      y += 16;
    }
  }

  // ═══ CROSS-CHECKS ═══
  y = ensureSpace(doc, y, 80);
  y = drawSectionHeader(doc, 'Cross-Checks', M, y, W);
  const checkRows: Array<{ cols: string[]; bold?: boolean }> = [
    { cols: ['Check', 'Expected', 'Actual', 'Status'], bold: true },
    ...calc.crossChecks.map((c) => ({
      cols: [c.label, c.expected, c.actual, c.match ? '✓ Pass' : '✗ Fail'],
    })),
  ];
  y = drawTable(doc, checkRows, [180, 110, 110, 80], M, y, W);

  // ═══ MONTHLY COMPARISON ═══
  y = ensureSpace(doc, y, 100);
  y = drawSectionHeader(doc, 'Monthly Comparison (last 6 periods)', M, y, W);
  const monthlyRows: Array<{ cols: string[]; bold?: boolean }> = [
    { cols: ['Period', 'Taxable', 'Output Tax', 'ITC', 'Net Payable'], bold: true },
    ...report.monthlyComparison.map((m) => ({
      cols: [
        m.periodLabel,
        `₹${m.taxableValue.toLocaleString('en-IN')}`,
        `₹${m.outputTax.toLocaleString('en-IN')}`,
        `₹${m.itc.toLocaleString('en-IN')}`,
        `₹${m.netPayable.toLocaleString('en-IN')}`,
      ],
    })),
  ];
  y = drawTable(doc, monthlyRows, [80, 110, 100, 100, 100], M, y, W);

  // ═══ ORACLE INSIGHTS ═══
  y = ensureSpace(doc, y, 100);
  y = drawSectionHeader(doc, 'Oracle Insights', M, y, W);
  doc.fillColor(DARK).fontSize(9).font('Helvetica');
  for (const insight of report.insights) {
    y = ensureSpace(doc, y, 30);
    const lines = doc.widthOfString(insight) > CW - 20
      ? doc.heightOfString(insight, { width: CW - 20 })
      : 12;
    doc.fillColor(GRAY).font('Helvetica-Bold').fontSize(8);
    doc.text('•', M, y);
    doc.fillColor(DARK).font('Helvetica').fontSize(9);
    doc.text(insight, M + 12, y, { width: CW - 20 });
    y += lines + 6;
  }

  // ═══ RECOMMENDATIONS ═══
  y = ensureSpace(doc, y, 80);
  y = drawSectionHeader(doc, 'Recommended Actions', M, y, W);
  doc.fillColor(EMERALD).font('Helvetica-Bold').fontSize(9);
  for (const rec of report.recommendations) {
    y = ensureSpace(doc, y, 30);
    doc.fillColor(EMERALD).font('Helvetica-Bold').fontSize(9);
    doc.text('→', M, y);
    doc.fillColor(DARK).font('Helvetica').fontSize(9);
    doc.text(rec, M + 14, y, { width: CW - 20 });
    y += doc.heightOfString(rec, { width: CW - 20 }) + 6;
  }

  // ═══ FOOTER ═══
  y = ensureSpace(doc, y, 40);
  y += 10;
  doc.save();
  doc.moveTo(M, y).lineTo(W - M, y).strokeColor(LIGHT_GRAY).lineWidth(1).stroke();
  doc.restore();
  y += 8;
  doc.fillColor(GRAY).fontSize(7).font('Helvetica');
  doc.text(
    `Generated by GSTPilot Oracle CFO™ on ${new Date(report.generatedAt).toLocaleString('en-IN')} by ${report.generatedBy}. Report ID: ${report.reportId}. This report is computed from live invoice data — verify with GSTR-2B before filing.`,
    M, y, { width: CW, align: 'center' },
  );

  doc.end();
  const buffer = await pdfPromise;
  return { buffer, base64: buffer.toString('base64') };
}

// ─── PDF drawing helpers ────────────────────────────────────────────────────

function drawSectionHeader(doc: any, title: string, M: number, y: number, W: number): number {
  y = ensureSpace(doc, y, 40);
  doc.save();
  doc.rect(M, y, 6, 16).fill(EMERALD);
  doc.restore();
  doc.fillColor(DARK).fontSize(12).font('Helvetica-Bold');
  doc.text(title, M + 12, y + 1);
  return y + 24;
}

function drawTable(
  doc: any,
  rows: Array<{ cols: string[]; bold?: boolean }>,
  colWidths: number[],
  M: number,
  y: number,
  W: number,
): number {
  const rowH = 16;
  for (let i = 0; i < rows.length; i++) {
    y = ensureSpace(doc, y, rowH);
    const row = rows[i];
    const isHeader = i === 0;
    doc.save();
    if (isHeader) {
      doc.rect(M, y, colWidths.reduce((s, w) => s + w, 0), rowH).fill(BG_LIGHT);
    } else if (i % 2 === 0) {
      doc.rect(M, y, colWidths.reduce((s, w) => s + w, 0), rowH).fill('#fafafa');
    }
    doc.restore();
    let x = M;
    for (let j = 0; j < row.cols.length; j++) {
      doc.fillColor(DARK).fontSize(8).font(row.bold ? 'Helvetica-Bold' : 'Helvetica');
      doc.text(row.cols[j], x + 4, y + 4, { width: colWidths[j] - 8 });
      x += colWidths[j];
    }
    y += rowH;
  }
  return y + 8;
}

function drawKeyValueTable(
  doc: any,
  rows: Array<{ cols: string[]; bold?: boolean; highlight?: boolean }>,
  M: number,
  y: number,
  W: number,
): number {
  const CW = W - M * 2;
  const labelW = CW * 0.6;
  const valueW = CW * 0.4;
  const rowH = 16;
  for (const row of rows) {
    y = ensureSpace(doc, y, rowH);
    doc.save();
    if (row.highlight) {
      doc.rect(M, y, CW, rowH).fill(EMERALD);
    } else if (row.bold) {
      doc.rect(M, y, CW, rowH).fill(BG_LIGHT);
    }
    doc.restore();
    doc.fillColor(row.highlight ? '#ffffff' : DARK).fontSize(9).font(row.bold ? 'Helvetica-Bold' : 'Helvetica');
    doc.text(row.cols[0], M + 8, y + 4, { width: labelW - 8 });
    doc.text(row.cols[1], M + labelW, y + 4, { width: valueW - 8, align: 'right' });
    y += rowH;
  }
  return y + 8;
}

function ensureSpace(doc: any, y: number, needed: number): number {
  if (y + needed > 800) {
    doc.addPage();
    return 50;
  }
  return y;
}

