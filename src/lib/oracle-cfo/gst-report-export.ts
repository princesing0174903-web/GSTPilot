// EXCEL EXPORT (xlsx / SheetJS)
// ═══════════════════════════════════════════════════════════════════════════════

export async function generateGSTReportExcel(report: GSTReport): Promise<{ buffer: Buffer; base64: string }> {
  const XLSX = await import('xlsx');
  const wb = XLSX.utils.book_new();

  // ── Sheet 1: Executive Summary ──
  const summaryAoa: (string | number)[][] = [
    ['GSTPilot — GST Report'],
    [`Report Type: ${report.intent.reportType.toUpperCase()}`],
    [`Period: ${report.intent.periodLabel} (${report.intent.startDate} to ${report.intent.endDate})`],
    [`Generated: ${new Date(report.generatedAt).toLocaleString('en-IN')} by ${report.generatedBy}`],
    [`Report ID: ${report.reportId}`],
    [],
    ['EXECUTIVE SUMMARY'],
    ['Metric', 'Value'],
    ['Taxable Turnover', report.calculations.totalTaxableTurnover],
    ['Total Output Tax', report.calculations.totalOutputTax],
    ['ITC Available', report.calculations.itcAvailable],
    ['ITC Utilized', report.calculations.itcUtilized],
    ['Net GST Payable', report.calculations.netPayable],
    ['Exempt Supplies', report.calculations.totalExempt],
    ['Zero-Rated Supplies', report.calculations.totalZeroRated],
    ['Export Supplies', report.calculations.totalExport],
    ['Refund Eligible', report.calculations.refundEligible],
    [],
    ['PERIOD DELTA'],
    ['Prior Period Output Tax', report.calculations.priorPeriodOutputTax],
    ['Current Output Tax', report.calculations.totalOutputTax],
    ['Delta', report.calculations.deltaOutputTax],
    ['Delta %', report.calculations.deltaPercent],
  ];
  const wsSummary = XLSX.utils.aoa_to_sheet(summaryAoa);
  wsSummary['!cols'] = [{ wch: 32 }, { wch: 22 }];
  XLSX.utils.book_append_sheet(wb, wsSummary, 'Summary');

  // ── Sheet 2: Sales by Slab ──
  const salesAoa: (string | number)[][] = [
    ['GST Slab', 'Invoice Count', 'Taxable Value', 'CGST', 'SGST', 'IGST', 'Cess', 'Total Tax', 'Total Amount'],
    ...report.calculations.salesBySlab.map((s) => [
      `${s.gstRate}%`, s.invoiceCount, s.taxableValue, s.cgst, s.sgst, s.igst, s.cess, s.totalTax, s.totalAmount,
    ]),
    ['TOTAL',
      report.calculations.salesBySlab.reduce((s, r) => s + r.invoiceCount, 0),
      report.calculations.totalTaxableTurnover,
      report.calculations.outputCGST,
      report.calculations.outputSGST,
      report.calculations.outputIGST,
      report.calculations.outputCess,
      report.calculations.totalOutputTax,
      report.calculations.totalTaxableTurnover + report.calculations.totalOutputTax,
    ],
  ];
  const wsSales = XLSX.utils.aoa_to_sheet(salesAoa);
  wsSales['!cols'] = [{ wch: 10 }, { wch: 14 }, { wch: 16 }, { wch: 14 }, { wch: 14 }, { wch: 14 }, { wch: 12 }, { wch: 14 }, { wch: 16 }];
  XLSX.utils.book_append_sheet(wb, wsSales, 'Sales by Slab');

  // ── Sheet 3: Purchases by Slab ──
  const purchaseAoa: (string | number)[][] = [
    ['GST Slab', 'Invoice Count', 'Taxable Value', 'CGST', 'SGST', 'IGST', 'Cess', 'Total ITC'],
    ...report.calculations.purchasesBySlab.map((s) => [
      `${s.gstRate}%`, s.invoiceCount, s.taxableValue, s.cgst, s.sgst, s.igst, s.cess, s.totalTax,
    ]),
    ['TOTAL',
      report.calculations.purchasesBySlab.reduce((s, r) => s + r.invoiceCount, 0),
      report.calculations.purchasesBySlab.reduce((s, r) => s + r.taxableValue, 0),
      report.calculations.itcCGST,
      report.calculations.itcSGST,
      report.calculations.itcIGST,
      report.calculations.itcCess,
      report.calculations.itcAvailable,
    ],
  ];
  const wsPurchase = XLSX.utils.aoa_to_sheet(purchaseAoa);
  wsPurchase['!cols'] = [{ wch: 10 }, { wch: 14 }, { wch: 16 }, { wch: 14 }, { wch: 14 }, { wch: 14 }, { wch: 12 }, { wch: 14 }];
  XLSX.utils.book_append_sheet(wb, wsPurchase, 'Purchases by Slab');

  // ── Sheet 4: GST Liability ──
  const liabilityAoa: (string | number)[][] = [
    ['Component', 'Amount (₹)'],
    ['Output CGST', report.calculations.outputCGST],
    ['Output SGST', report.calculations.outputSGST],
    ['Output IGST', report.calculations.outputIGST],
    ['Output Cess', report.calculations.outputCess],
    ['Total Output Tax', report.calculations.totalOutputTax],
    ['Less: ITC Utilized', -report.calculations.itcUtilized],
    ['Net CGST Payable', report.calculations.netCGSTPayable],
    ['Net SGST Payable', report.calculations.netSGSTPayable],
    ['Net IGST Payable', report.calculations.netIGSTPayable],
    ['Net Cess Payable', report.calculations.netCessPayable],
    ['Net GST Payable', report.calculations.netPayable],
  ];
  const wsLiability = XLSX.utils.aoa_to_sheet(liabilityAoa);
  wsLiability['!cols'] = [{ wch: 28 }, { wch: 18 }];
  XLSX.utils.book_append_sheet(wb, wsLiability, 'GST Liability');

  // ── Sheet 5: ITC Summary ──
  const itcAoa: (string | number)[][] = [
    ['Component', 'Amount (₹)'],
    ['ITC Available (CGST)', report.calculations.itcCGST],
    ['ITC Available (SGST)', report.calculations.itcSGST],
    ['ITC Available (IGST)', report.calculations.itcIGST],
    ['ITC Available (Cess)', report.calculations.itcCess],
    ['Total ITC Available', report.calculations.itcAvailable],
    ['ITC Reversed (Rule 42/43)', -report.calculations.itcReversed],
    ['ITC Utilized', report.calculations.itcUtilized],
    ['Refund Eligible', report.calculations.refundEligible],
  ];
  const wsItc = XLSX.utils.aoa_to_sheet(itcAoa);
  wsItc['!cols'] = [{ wch: 30 }, { wch: 18 }];
  XLSX.utils.book_append_sheet(wb, wsItc, 'ITC Summary');

  // ── Sheet 6: Top Customers ──
  const custAoa: (string | number)[][] = [
    ['Customer', 'GSTIN', 'Invoice Count', 'Taxable Value', 'Tax Amount', 'Total Amount'],
    ...report.topCustomers.map((c) => [c.name, c.gstin ?? '', c.invoiceCount, c.taxableValue, c.taxAmount, c.totalAmount]),
  ];
  const wsCust = XLSX.utils.aoa_to_sheet(custAoa);
  wsCust['!cols'] = [{ wch: 30 }, { wch: 18 }, { wch: 14 }, { wch: 16 }, { wch: 16 }, { wch: 16 }];
  XLSX.utils.book_append_sheet(wb, wsCust, 'Top Customers');

  // ── Sheet 7: Top Vendors ──
  const vendAoa: (string | number)[][] = [
    ['Vendor', 'GSTIN', 'Invoice Count', 'Taxable Value', 'ITC Amount', 'Total Amount'],
    ...report.topVendors.map((v) => [v.name, v.gstin ?? '', v.invoiceCount, v.taxableValue, v.taxAmount, v.totalAmount]),
  ];
  const wsVend = XLSX.utils.aoa_to_sheet(vendAoa);
  wsVend['!cols'] = [{ wch: 30 }, { wch: 18 }, { wch: 14 }, { wch: 16 }, { wch: 16 }, { wch: 16 }];
  XLSX.utils.book_append_sheet(wb, wsVend, 'Top Vendors');

  // ── Sheet 8: Validation Issues ──
  const valAoa: (string | number)[][] = [
    ['Invoice ID', 'Invoice Number', 'Severity', 'Field', 'Message', 'Value'],
    ...report.validation.issues.map((i) => [i.invoiceId, i.invoiceNumber, i.severity, i.field, i.message, i.value]),
  ];
  const wsVal = XLSX.utils.aoa_to_sheet(valAoa);
  wsVal['!cols'] = [{ wch: 26 }, { wch: 18 }, { wch: 10 }, { wch: 14 }, { wch: 60 }, { wch: 22 }];
  XLSX.utils.book_append_sheet(wb, wsVal, 'Validation Issues');

  // ── Sheet 9: Monthly Comparison ──
  const monthlyAoa: (string | number)[][] = [
    ['Period', 'Taxable Value', 'Output Tax', 'ITC', 'Net Payable'],
    ...report.monthlyComparison.map((m) => [m.periodLabel, m.taxableValue, m.outputTax, m.itc, m.netPayable]),
  ];
  const wsMonthly = XLSX.utils.aoa_to_sheet(monthlyAoa);
  wsMonthly['!cols'] = [{ wch: 14 }, { wch: 16 }, { wch: 14 }, { wch: 14 }, { wch: 14 }];
  XLSX.utils.book_append_sheet(wb, wsMonthly, 'Monthly Comparison');

  // ── Sheet 10: Cross-Checks ──
  const checkAoa: (string | number)[][] = [
    ['Check', 'Expected', 'Actual', 'Status'],
    ...report.calculations.crossChecks.map((c) => [c.label, c.expected, c.actual, c.match ? 'PASS' : 'FAIL']),
  ];
  const wsCheck = XLSX.utils.aoa_to_sheet(checkAoa);
  wsCheck['!cols'] = [{ wch: 36 }, { wch: 18 }, { wch: 18 }, { wch: 10 }];
  XLSX.utils.book_append_sheet(wb, wsCheck, 'Cross-Checks');

  // ── Sheet 11: Oracle Insights ──
  const insightsAoa: (string | number)[][] = [
    ['#', 'Insight'],
    ...report.insights.map((s, i) => [i + 1, s]),
    [],
    ['RECOMMENDED ACTIONS'],
    ...report.recommendations.map((s, i) => [i + 1, s]),
  ];
  const wsInsights = XLSX.utils.aoa_to_sheet(insightsAoa);
  wsInsights['!cols'] = [{ wch: 6 }, { wch: 100 }];
  XLSX.utils.book_append_sheet(wb, wsInsights, 'Oracle Insights');

  // Write to buffer
  const arrayBuffer = XLSX.write(wb, { type: 'array', bookType: 'xlsx' }) as ArrayBuffer;
  const buffer = Buffer.from(arrayBuffer);
  return { buffer, base64: buffer.toString('base64') };
}

